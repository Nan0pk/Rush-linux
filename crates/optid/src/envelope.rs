    // ── Golden JSON test ───────────────────────────────────────────

    #[test]
    fn f3_envelope_golden_json_is_stable() {
        // A fixed golden JSON that the status surface emits. If the
        // schema changes, this test fails and the contributor must
        // update the golden JSON AND bump schema_version.
        let golden = r#"{
  "schema_version": 1,
  "timestamp": 1000,
  "correlation_id": "golden-1",
  "snapshot": {
    "on_ac": true,
    "battery_pct": 80,
    "thermal_c": 45.0,
    "loadavg_1": 0.5,
    "cpu_pressure_avg10": 1.0,
    "memory_pressure_avg10": 2.0,
    "io_pressure_avg10": 3.0,
    "zram_swap_active": true,
    "is_vm_guest": false,
    "workload_class": "interactive",
    "mode": "balanced"
  },
  "domains": [
    {
      "domain": "cpu_epp",
      "support": "supported",
      "mode": "actuate",
      "gate": "permitted",
      "last_apply": {
        "timestamp": 990,
        "action": "cpu.epp=balance_performance",
        "result": {
          "applied": {
            "written_value": "balance_performance"
          }
        },
        "correlation_id": "golden-1"
      }
    }
  ]
}"#;
        let envelope = ObservationEnvelope::from_json(golden).unwrap();
        let re_serialized = envelope.to_json().unwrap();
        // The re-serialized JSON must match the golden byte-for-byte
        // (modulo whitespace, which we normalize for comparison).
        let normalized_golden: String = golden.split_whitespace().collect();
        let normalized_actual: String = re_serialized.split_whitespace().collect();
        assert_eq!(
            normalized_golden, normalized_actual,
            "golden JSON must round-trip losslessly"
        );
    }

