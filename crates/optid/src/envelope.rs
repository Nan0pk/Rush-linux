    // ── ApplyResult: unsupported ≠ skipped ≠ failed ────────────────

    #[test]
    fn f3_apply_result_variants_are_distinct() {
        let applied = ApplyResult::Applied {
            written_value: "60".to_string(),
        };
        let skipped = ApplyResult::Skipped {
            reason: "dry-run".to_string(),
        };
        let failed = ApplyResult::Failed {
            error: "EBUSY".to_string(),
        };
        let drifted = ApplyResult::Drifted {
            expected: "60".to_string(),
            actual: "100".to_string(),
        };
        let restored = ApplyResult::Restored {
            original: "100".to_string(),
        };
        // All five variants are distinct.
        assert_ne!(applied, skipped);
        assert_ne!(applied, failed);
        assert_ne!(applied, drifted);
        assert_ne!(applied, restored);
        assert_ne!(skipped, failed);
        assert_ne!(skipped, drifted);
        assert_ne!(skipped, restored);
        assert_ne!(failed, drifted);
        assert_ne!(failed, restored);
        assert_ne!(drifted, restored);
    }

    // ── RestoreResult: restored ≠ stabilized ≠ relinquished ────────

    #[test]
    fn f3_restore_result_variants_are_distinct() {
        let restored = RestoreResult::Restored {
            original: "100".to_string(),
        };
        let stabilized = RestoreResult::Stabilized {
            fallback: "default".to_string(),
            reason: "original unreadable".to_string(),
        };
        let relinquished = RestoreResult::Relinquished {
            reason: "external change detected".to_string(),
        };
        let failed = RestoreResult::Failed {
            error: "EIO".to_string(),
        };
        assert_ne!(restored, stabilized);
        assert_ne!(restored, relinquished);
        assert_ne!(restored, failed);
        assert_ne!(stabilized, relinquished);
        assert_ne!(stabilized, failed);
        assert_ne!(relinquished, failed);
    }

